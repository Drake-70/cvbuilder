const STYLES = {
  success: 'bg-emerald-50 border-emerald-200 text-emerald-800',
  error: 'bg-rose-50 border-rose-200 text-rose-800',
  info: 'bg-brand-50 border-brand-200 text-brand-800',
  warning: 'bg-amber-50 border-amber-200 text-amber-800'
};

const ICON_COLORS = {
  success: 'text-emerald-500',
  error: 'text-rose-500',
  info: 'text-brand-500',
  warning: 'text-amber-500'
};

function ToastContainer({ toasts, onRemove }) {
  if (toasts.length === 0) return null;

  return (
    <div className="fixed bottom-4 right-4 z-[100] flex flex-col gap-2 max-w-sm w-full pointer-events-none" role="status" aria-live="polite">
      {toasts.map((t) => (
        <div
          key={t.id}
          className={`pointer-events-auto flex items-start gap-3 p-4 rounded-xl border shadow-lg animate-slide-up ${STYLES[t.type]}`}
        >
          <span className={`flex-shrink-0 mt-0.5 ${ICON_COLORS[t.type]}`}>
            {ICONS[t.type]}
          </span>
          <div className="flex-1 min-w-0">
            {t.title && <p className="font-semibold text-sm">{t.title}</p>}
            {t.message && <p className="text-sm opacity-80 mt-0.5">{t.message}</p>}
          </div>
          <button
            onClick={() => onRemove(t.id)}
            className="flex-shrink-0 p-0.5 rounded hover:bg-black/5 cursor-pointer transition-colors opacity-50 hover:opacity-100"
            aria-label="Dismiss"
          >
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
              <line x1="18" y1="6" x2="6" y2="18" /><line x1="6" y1="6" x2="18" y2="18" />
            </svg>
          </button>
        </div>
      ))}
    </div>
  );
}
